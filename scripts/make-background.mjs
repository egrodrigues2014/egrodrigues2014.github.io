#!/usr/bin/env node
/**
 * Generates assets/images/site/background.jpg's replacement: a dark gradient PNG
 * for the hero.
 *
 * WHY THIS SCRIPT EXISTS AT ALL
 *
 * The background it replaced shipped with the theme's example site: 354,464 bytes
 * of business-vector illustration that also carried a mandatory Freepik
 * attribution. Removing it removes the attribution obligation with it.
 *
 * It has to be a raster image. `partials/sections/home.html` calls `$src.Resize`
 * four times on the background and reads `$src.Width`, with no guard for SVG —
 * and Hugo cannot resize SVG, so an SVG background fails the build. That ruled
 * out the obvious approach.
 *
 * WHY IT IS HAND-ROLLED
 *
 * No image library. package.json is generated by `hugo mod npm pack` and rewritten
 * by every `mise run install`, so a dependency added there would not survive; and
 * pulling one into scripts/package.json to draw a gradient is disproportionate.
 * PNG is a simple enough container to emit directly: a signature, IHDR, one
 * zlib-compressed IDAT and IEND, with a CRC32 per chunk. Node's zlib does the
 * only hard part.
 *
 * The output is committed, so a build never depends on running this. The script is
 * here so the image is reproducible and reviewable rather than a binary that
 * appeared from nowhere: re-run it, and you get the same bytes.
 *
 *   node scripts/make-background.mjs
 */
import fs from 'node:fs'
import path from 'node:path'
import zlib from 'node:zlib'
import { REPO } from './lib.mjs'

// 1500 is the exact right width, not a round number. `home.html:43-46` resizes the
// background to 500 / 800 / 1200 / 1500 and serves those; it never serves anything
// wider. It also guards with `{{ if lt $src.Width "1500" }}` to avoid upscaling a
// small source. So 1500 satisfies the guard while wasting no pixels — a 1920-wide
// source measured 64.8 KB, and every one of those extra bytes was discarded.
const WIDTH = 1500
const HEIGHT = 844 // 16:9
const OUT = path.join(REPO, 'assets/images/site/background.png')

if (WIDTH < 1500) throw new Error('width must stay >= 1500 or the theme takes its small-source branch')

/**
 * Vertical gradient between two dark slate tones, with a slight horizontal lift
 * towards the top-left so the hero has some direction rather than reading as a
 * flat fill.
 *
 * Both endpoints are dark: the hero prints light text over this in BOTH themes
 * (darkBackground is not set), so a light stop anywhere would fail contrast in
 * one of them.
 */
const TOP = [15, 30, 45] // deep slate, slightly blue
const BOTTOM = [7, 13, 20] // near-black

/** Ordered dithering. A smooth 8-bit ramp over 1080 rows bands visibly; scattering
 *  the rounding error with a 4x4 Bayer matrix costs nothing and removes it. */
const BAYER = [
  [0, 8, 2, 10],
  [12, 4, 14, 6],
  [3, 11, 1, 9],
  [15, 7, 13, 5]
]

const raw = Buffer.alloc(HEIGHT * (WIDTH * 3 + 1))
let p = 0
for (let y = 0; y < HEIGHT; y++) {
  raw[p++] = 0 // PNG filter type 0 (None) for this scanline
  const v = y / (HEIGHT - 1)
  // Ease the ramp so the darkening is faster near the bottom than a straight line.
  const t = v * v * (3 - 2 * v)
  for (let x = 0; x < WIDTH; x++) {
    // Radial lift centred off the top-left corner, strongest at 0 and gone by ~70%.
    const dx = x / WIDTH
    const dy = y / HEIGHT
    const d = Math.sqrt(dx * dx + dy * dy)
    const lift = Math.max(0, 1 - d / 0.7) * 10
    const dither = (BAYER[y & 3][x & 3] + 0.5) / 16 - 0.5
    for (let c = 0; c < 3; c++) {
      const base = TOP[c] + (BOTTOM[c] - TOP[c]) * t + lift
      raw[p++] = Math.max(0, Math.min(255, Math.round(base + dither)))
    }
  }
}

// --- minimal PNG container -------------------------------------------------
const CRC_TABLE = (() => {
  const t = new Int32Array(256)
  for (let n = 0; n < 256; n++) {
    let c = n
    for (let k = 0; k < 8; k++) c = c & 1 ? 0xedb88320 ^ (c >>> 1) : c >>> 1
    t[n] = c
  }
  return t
})()

const crc32 = (buf) => {
  let c = -1
  for (let i = 0; i < buf.length; i++) c = CRC_TABLE[(c ^ buf[i]) & 0xff] ^ (c >>> 8)
  return (c ^ -1) >>> 0
}

const chunk = (type, data) => {
  const len = Buffer.alloc(4)
  len.writeUInt32BE(data.length)
  const body = Buffer.concat([Buffer.from(type, 'ascii'), data])
  const crc = Buffer.alloc(4)
  crc.writeUInt32BE(crc32(body))
  return Buffer.concat([len, body, crc])
}

const ihdr = Buffer.alloc(13)
ihdr.writeUInt32BE(WIDTH, 0)
ihdr.writeUInt32BE(HEIGHT, 4)
ihdr[8] = 8 // bit depth
ihdr[9] = 2 // colour type 2 = truecolour RGB
ihdr[10] = 0 // deflate
ihdr[11] = 0 // adaptive filtering
ihdr[12] = 0 // no interlace

const png = Buffer.concat([
  Buffer.from([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a]),
  chunk('IHDR', ihdr),
  chunk('IDAT', zlib.deflateSync(raw, { level: 9 })),
  chunk('IEND', Buffer.alloc(0))
])

fs.writeFileSync(OUT, png)

const kb = (n) => `${(n / 1024).toFixed(1)} KB`
console.log(`wrote ${path.relative(REPO, OUT)} — ${WIDTH}x${HEIGHT}, ${kb(png.length)}`)
console.log(`(the theme's background.jpg it replaces was ${kb(354464)})`)
